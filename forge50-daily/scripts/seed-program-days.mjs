#!/usr/bin/env node
// Generates the program_days seed from Forge50_Training_App.html.
//
//   node scripts/seed-program-days.mjs path/to/Forge50_Training_App.html > supabase/seed/program_days.sql
//
// The HTML app encodes the program as three script constants:
//   SCHED       day of week (JS getDay, 0 = Sunday) -> session key, name, type
//   PRES        phase (1-3) -> session key -> prescription string
//   PHASE_NAME  phase -> name
// plus phaseOf(week): weeks 1-16 are phase 1, 17-32 phase 2, 33-52 phase 3.
// This script extracts those from the file (rather than copying them) and
// expands them to 52 weeks x 7 days. The SQL upserts on (week, day_of_week),
// so re-running it is safe.
import fs from "node:fs";
import vm from "node:vm";

const file = process.argv[2];
if (!file) {
  console.error("usage: seed-program-days.mjs <Forge50_Training_App.html>");
  process.exit(1);
}
const html = fs.readFileSync(file, "utf8");

function extractConst(name) {
  const start = html.indexOf(`const ${name} =`);
  if (start < 0) throw new Error(`const ${name} not found`);
  const open = html.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < html.length; i++) {
    if (html[i] === "{") depth++;
    else if (html[i] === "}" && --depth === 0) {
      return vm.runInNewContext(`(${html.slice(open, i + 1)})`);
    }
  }
  throw new Error(`const ${name} is unterminated`);
}

function extractPhaseOf() {
  const m = html.match(/function phaseOf\(wk\)\{([^}]*)\}/);
  if (!m) throw new Error("phaseOf not found");
  return vm.runInNewContext(`(function(wk){${m[1]}})`);
}

const SCHED = extractConst("SCHED");
const PRES = extractConst("PRES");
const PHASE_NAME = extractConst("PHASE_NAME");
const phaseOf = extractPhaseOf();

// The hero line the app shows under each session type.
const TYPE_NOTE = {
  Cardio: "Rowing day — kettlebells stay put.",
  Mobility: "Move gently and let the hard work sink in.",
  Strength: "Today is a kettlebell day — the rower rests.",
  MetCon: "Today is a kettlebell day — the rower rests.",
};

// "Goblet squat 4×8 (16kg)" -> { name, sets, reps, load }. Anything that is
// not "<name> <sets>×<reps> (<detail>)" stays as plain text. The original
// text is always kept.
function parseItem(text) {
  const m = text.match(/^(.*[A-Za-z].*?)\s+(\d+)×(\S+)(?:\s+\((.+)\))?$/);
  if (!m) return { text };
  const [, name, sets, reps, detail] = m;
  const item = { text, name, sets: Number(sets), reps };
  if (detail) item[/^\d+(\.\d+)?\s?kg$/.test(detail) ? "load" : "note"] = detail;
  return item;
}

function parsePrescription(raw) {
  const parts = raw.split(" · ").map((s) => s.trim());
  let format = null;
  // "4 rounds — 10 swings…", "AMRAP 20 min — …", "For time — …" set the
  // structure for the whole session.
  const lead = parts[0].match(/^(\d+ rounds|AMRAP \d+ min|For time) — (.+)$/);
  if (lead) {
    format = lead[1];
    parts[0] = lead[2];
  }
  return { format, items: parts.map(parseItem) };
}

const sql = (v) => (v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);

// One row per (phase, day of week): 21 distinct sessions. Postgres expands
// them to 52 weeks using the same week -> phase boundaries as phaseOf().
const weeksByPhase = {};
for (let week = 1; week <= 52; week++) {
  const phase = phaseOf(week);
  const r = (weeksByPhase[phase] ??= { from: week, to: week });
  r.to = week;
}

const rows = [];
for (const phase of Object.keys(PRES).map(Number)) {
  for (let dow = 0; dow <= 6; dow++) {
    const s = SCHED[dow];
    const raw = PRES[phase][s.key];
    const prescription = {
      phase,
      phase_name: PHASE_NAME[phase],
      session_key: s.key,
      text: raw,
      ...parsePrescription(raw),
    };
    rows.push(
      `  (${phase}, ${dow}, ${sql(s.type)}, ${sql(s.name)}, ${sql(JSON.stringify(prescription))}::jsonb, ${sql(TYPE_NOTE[s.type] ?? null)})`,
    );
  }
}

const phaseRanges = Object.entries(weeksByPhase)
  .map(([phase, { from, to }]) => `  (${phase}, ${from}, ${to})`)
  .join(",\n");

process.stdout.write(`-- Generated by scripts/seed-program-days.mjs from Forge50_Training_App.html.
-- 52 weeks x 7 days; day_of_week is JS getDay (0 = Sunday). Re-runnable.
with phases (phase, first_week, last_week) as (
  values
${phaseRanges}
),
sessions (phase, day_of_week, session_type, title, prescription, notes) as (
  values
${rows.join(",\n")}
)
insert into public.program_days (week, day_of_week, session_type, title, prescription, notes)
select w.week, s.day_of_week, s.session_type, s.title, s.prescription, s.notes
from phases p
cross join lateral generate_series(p.first_week, p.last_week) as w(week)
join sessions s on s.phase = p.phase
order by w.week, s.day_of_week
on conflict (week, day_of_week) do update set
  session_type = excluded.session_type,
  title = excluded.title,
  prescription = excluded.prescription,
  notes = excluded.notes;
`);
